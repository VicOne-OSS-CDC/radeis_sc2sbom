#[test]
fn test_parse_pipfile_lock_basic() {
    let content = r#"{
    "_meta": {
        "hash": {
            "sha256": "abc123"
        },
        "pipfile-spec": 6
    },
    "default": {
        "azure-identity": {
            "hashes": [
                "sha256:7cca6ab79b62bb6a56f831d5bd6b0188f0a11d528e55a40c3d1e17ad031f00cb",
                "sha256:def456"
            ],
            "index": "pypi",
            "version": "==1.12.0"
        },
        "requests": {
            "hashes": [
                "sha256:abc789"
            ],
            "version": "==2.31.0"
        }
    },
    "develop": {}
}"#;

    let mut temp_file = NamedTempFile::new().unwrap();
    temp_file.write_all(content.as_bytes()).unwrap();
    temp_file.flush().unwrap();

    let data = parse_pipfile_lock_with_relationships(temp_file.path(), false).unwrap();
    let deps = data.dependencies;

    assert_eq!(deps.len(), 2);

    let azure_identity = deps.iter().find(|d| d.name == "azure-identity").unwrap();
    assert_eq!(azure_identity.version, "1.12.0");
    assert_eq!(azure_identity.ecosystem, "pip");
    assert_eq!(azure_identity.source, DependencySource::LockFile);
    assert!(!azure_identity.is_dev);
    assert!(azure_identity.is_direct); // Has index field
    assert_eq!(
        azure_identity.checksum_sha256,
        Some("7cca6ab79b62bb6a56f831d5bd6b0188f0a11d528e55a40c3d1e17ad031f00cb".to_string())
    );

    let requests = deps.iter().find(|d| d.name == "requests").unwrap();
    assert_eq!(requests.version, "2.31.0");
    assert!(!requests.is_direct); // No index field = transitive
    assert_eq!(requests.checksum_sha256, Some("abc789".to_string()));
}


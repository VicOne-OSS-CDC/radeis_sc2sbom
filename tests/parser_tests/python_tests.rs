#[test]
fn test_parse_pipfile_version_specs() {
    let content = r#"
[packages]
package1 = "*"
package2 = ">=1.0"
package3 = "==2.0.0"
package4 = "~=1.2.0"
package5 = {version = ">=3.0", extras = ["dev"]}
package6 = {version = "==1.5.0"}
package7 = {version = "*"}

[dev-packages]
"#;

    let mut temp_file = NamedTempFile::new().unwrap();
    temp_file.write_all(content.as_bytes()).unwrap();
    temp_file.flush().unwrap();

    let deps = parse_pipfile(temp_file.path(), false).unwrap();

    assert_eq!(deps.len(), 7);

    let pkg1 = deps.iter().find(|d| d.name == "package1").unwrap();
    assert_eq!(pkg1.version, "unspecified");

    let pkg2 = deps.iter().find(|d| d.name == "package2").unwrap();
    assert_eq!(pkg2.version, ">=1.0");

    let pkg3 = deps.iter().find(|d| d.name == "package3").unwrap();
    assert_eq!(pkg3.version, "2.0.0"); // "==" stripped

    let pkg4 = deps.iter().find(|d| d.name == "package4").unwrap();
    assert_eq!(pkg4.version, "~=1.2.0");

    let pkg5 = deps.iter().find(|d| d.name == "package5").unwrap();
    assert_eq!(pkg5.version, ">=3.0");

    let pkg6 = deps.iter().find(|d| d.name == "package6").unwrap();
    assert_eq!(pkg6.version, "1.5.0"); // "==" stripped from table spec

    let pkg7 = deps.iter().find(|d| d.name == "package7").unwrap();
    assert_eq!(pkg7.version, "unspecified"); // "*" in table spec normalized to "unspecified"
}


#[test]
fn test_checksum_extraction_pipfile_lock() {
    let content = r#"{
    "_meta": {},
    "default": {
        "package-with-hashes": {
            "hashes": [
                "sha256:abc123def456",
                "sha256:ghi789jkl012"
            ],
            "version": "==1.0.0"
        },
        "package-no-hashes": {
            "hashes": [],
            "version": "==2.0.0"
        }
    },
    "develop": {}
}"#;

    let mut temp_file = NamedTempFile::new().unwrap();
    temp_file.write_all(content.as_bytes()).unwrap();
    temp_file.flush().unwrap();

    let data = parse_pipfile_lock_with_relationships(temp_file.path(), false).unwrap();
    let deps = data.dependencies;

    let with_hash = deps
        .iter()
        .find(|d| d.name == "package-with-hashes")
        .unwrap();
    assert_eq!(with_hash.checksum_sha256, Some("abc123def456".to_string()));

    let no_hash = deps.iter().find(|d| d.name == "package-no-hashes").unwrap();
    assert_eq!(no_hash.checksum_sha256, None);
}


#[test]
fn test_parse_requirements_txt_with_operators() {
    // v1.0.0: Non-exact version specs now return "unspecified" to avoid misleading version info
    // Only exact pins (== or =) are extracted as actual versions
    let content = r#"reportlab>=4.0.0
python-docx==1.1.0
matplotlib~=3.7.0
pillow<=10.0.0
pandas>2.0.0
numpy<1.24.0
requests!=2.28.0
flask>=2.0,<3.0
Django[bcrypt]==3.2.0
# Comment line
"#;

    let mut temp_file = NamedTempFile::new().unwrap();
    temp_file.write_all(content.as_bytes()).unwrap();
    temp_file.flush().unwrap();

    let deps = parse_requirements_txt(temp_file.path()).unwrap();

    assert_eq!(deps.len(), 9);

    // Non-exact specs should return "unspecified"
    let reportlab = deps.iter().find(|d| d.name == "reportlab").unwrap();
    assert_eq!(reportlab.version, "unspecified");
    assert_eq!(reportlab.ecosystem, "pip");

    // Exact pin with == should extract version
    let python_docx = deps.iter().find(|d| d.name == "python-docx").unwrap();
    assert_eq!(python_docx.version, "1.1.0");

    // Django with extra and exact pin
    let django = deps.iter().find(|d| d.name == "Django[bcrypt]").unwrap();
    assert_eq!(django.version, "3.2.0");
}


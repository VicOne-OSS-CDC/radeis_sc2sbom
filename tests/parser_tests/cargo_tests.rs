use radeis_sc2sbom::models::DependencySource;
use radeis_sc2sbom::parsers::cargo::{parse_cargo_lock_with_relationships, parse_cargo_toml};
use std::io::Write;
use tempfile::NamedTempFile;

#[test]
fn test_parse_cargo_toml_simple_versions() {
    let content = r#"
[package]
name = "test-project"
version = "0.1.0"

[dependencies]
serde = "1.0"
tokio = "1.20.0"
anyhow = "1.0.57"
"#;

    let mut temp_file = NamedTempFile::new().unwrap();
    temp_file.write_all(content.as_bytes()).unwrap();
    temp_file.flush().unwrap();

    let deps = parse_cargo_toml(temp_file.path()).unwrap();

    assert_eq!(deps.len(), 3);

    let serde = deps.iter().find(|d| d.name == "serde").unwrap();
    assert_eq!(serde.version, "1.0");
    assert_eq!(serde.ecosystem, "cargo");

    let tokio = deps.iter().find(|d| d.name == "tokio").unwrap();
    assert_eq!(tokio.version, "1.20.0");
}

